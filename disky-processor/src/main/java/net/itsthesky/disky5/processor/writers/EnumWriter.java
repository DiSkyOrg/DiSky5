package net.itsthesky.disky5.processor.writers;

import com.squareup.javapoet.*;
import net.itsthesky.disky5.processor.DiSkyProcessor;
import net.itsthesky.disky5.processor.util.NameUtils;
import net.itsthesky.disky5.processor.util.SkriptTypes;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.util.ArrayList;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

public final class EnumWriter {

    private static final String PACKAGE = "net.itsthesky.disky5.generated";
    private static final String CLASS_NAME = "GeneratedEnums";
    private static final ClassName REGISTRY =
        ClassName.get("net.itsthesky.disky5.api.syntax", "DiSkySyntaxRegistry");
    private static final ClassName LOCALE = ClassName.get(Locale.class);

    public static void write(ProcessingEnvironment env, Collection<DiSkyProcessor.EnumInfo> enums) throws IOException {
        MethodSpec.Builder register = MethodSpec.methodBuilder("register")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC);

        List<MethodSpec> perEnum = new ArrayList<>();
        for (DiSkyProcessor.EnumInfo e : enums) {
            String method = "register" + NameUtils.toClassName(e.codeName());
            register.addStatement("$N()", method);
            perEnum.add(buildRegisterMethod(method, e));
        }

        TypeSpec cls = TypeSpec.classBuilder(CLASS_NAME)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build())
            .addMethod(register.build())
            .addMethods(perEnum)
            .build();

        JavaFile.builder(PACKAGE, cls).build().writeTo(env.getFiler());
    }

    private static MethodSpec buildRegisterMethod(String method, DiSkyProcessor.EnumInfo e) {
        ClassName jda = e.jdaType();
        TypeName mapLiterals = ParameterizedTypeName.get(ClassName.get(Map.class), ClassName.get(String.class), jda);
        TypeName listStr = ParameterizedTypeName.get(ClassName.get(List.class), ClassName.get(String.class));

        TypeSpec parser = TypeSpec.anonymousClassBuilder("")
            .addSuperinterface(ParameterizedTypeName.get(SkriptTypes.PARSER, jda))
            .addMethod(MethodSpec.methodBuilder("canParse")
                .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
                .returns(boolean.class).addParameter(SkriptTypes.PARSE_CONTEXT, "context")
                .addStatement("return true").build())
            .addMethod(MethodSpec.methodBuilder("parse")
                .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
                .returns(jda).addParameter(String.class, "s").addParameter(SkriptTypes.PARSE_CONTEXT, "context")
                .addStatement("return literals.get(s.toLowerCase($T.ROOT).trim())", LOCALE).build())
            .addMethod(MethodSpec.methodBuilder("toString")
                .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
                .returns(String.class).addParameter(jda, "o").addParameter(int.class, "flags")
                .addStatement("return o.name().toLowerCase($T.ROOT).replace('_', ' ')", LOCALE).build())
            .addMethod(MethodSpec.methodBuilder("toVariableNameString")
                .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
                .returns(String.class).addParameter(jda, "o")
                .addStatement("return $S + o.name()", e.codeName() + ":").build())
            .build();

        MethodSpec.Builder m = MethodSpec.methodBuilder(method)
            .addModifiers(Modifier.PRIVATE, Modifier.STATIC);

        m.beginControlFlow("if ($T.getExactClassInfo($T.class) != null)", SkriptTypes.CLASSES, jda)
            .addStatement("return")
            .endControlFlow();

        m.addStatement("final $T literals = new $T<>()", mapLiterals, ClassName.get(LinkedHashMap.class));
        m.beginControlFlow("for ($T c : $T.values())", jda, jda)
            .addStatement("literals.put(c.name().toLowerCase($T.ROOT).replace('_', ' '), c)", LOCALE)
            .endControlFlow();
        if (e.aliasMethod() != null) {
            TypeName aliasMap = ParameterizedTypeName.get(
                ClassName.get(Map.class), jda, ArrayTypeName.of(ClassName.get(String.class)));
            m.addStatement("final $T aliasMap = $T.$N()", aliasMap, e.holder(), e.aliasMethod());
            m.beginControlFlow("for ($T key : aliasMap.keySet())", jda)
                .beginControlFlow("for ($T alias : aliasMap.get(key))", String.class)
                .addStatement("literals.put(alias.toLowerCase($T.ROOT).trim(), key)", LOCALE)
                .endControlFlow()
                .endControlFlow();
        }

        m.addStatement("final $T canonical = new $T<>()", listStr, ClassName.get(ArrayList.class));
        m.beginControlFlow("for ($T c : $T.values())", jda, jda)
            .addStatement("canonical.add(c.name().toLowerCase($T.ROOT).replace('_', ' '))", LOCALE)
            .endControlFlow();

        m.addStatement("$T.registerClass(new $T<>($T.class, $S).user($S).name($S).parser($L)"
                + ".usage(canonical.toArray(new $T[0])))",
            SkriptTypes.CLASSES, SkriptTypes.CLASS_INFO, jda, e.codeName(),
            e.userPattern(), e.displayName(), parser, String.class);
        m.addStatement("$T.INSTANCE.addEnumType($S, $S, canonical)",
            REGISTRY, e.codeName(), e.displayName());

        return m.build();
    }
}
