package net.itsthesky.disky5.processor.writers;

import net.itsthesky.disky5.processor.util.Versions;
import com.squareup.javapoet.*;
import net.itsthesky.disky5.annotations.docs.Documentation;
import net.itsthesky.disky5.processor.DiSkyProcessor.SyntaxRecord;
import net.itsthesky.disky5.processor.handlers.EffectHandler.EffectSpec;
import net.itsthesky.disky5.processor.handlers.EffectHandler.Param;
import net.itsthesky.disky5.processor.util.DocsUtils;
import net.itsthesky.disky5.processor.util.Log;
import net.itsthesky.disky5.processor.util.SkriptTypes;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.util.ArrayList;
import java.util.Collection;
import java.util.List;

public final class EffectWriter {

    private EffectWriter() {}

    private static final String PKG = "net.itsthesky.disky5.generated";

    private static final String REASON_PATTERN = " [(due to|because of|with [the] reason) %-string%]";

    public static void write(ProcessingEnvironment env, Collection<EffectSpec> specs,
                             List<String> generatedClasses, List<SyntaxRecord> syntaxRecords)
            throws IOException {
        for (EffectSpec spec : specs) {
            writeEffectClass(env, spec);
            generatedClasses.add(PKG + "." + spec.className());
            recordManifest(spec, syntaxRecords);
        }
    }

    private static void writeEffectClass(ProcessingEnvironment env, EffectSpec spec) throws IOException {
        List<String> patterns = patterns(spec);

        TypeSpec.Builder cls = TypeSpec.classBuilder(spec.className())
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .superclass(SkriptTypes.ASYNC_EFFECT);

        DocsUtils.attachDocumentation(cls, spec.docs());

        CodeBlock.Builder reg = CodeBlock.builder()
            .add("$T.registerEffect($L.class", SkriptTypes.SKRIPT, spec.className());
        for (String pattern : patterns)
            reg.add(",\n$S", pattern);
        reg.add(");\n");
        cls.addStaticBlock(reg.build());

        for (int i = 0; i < spec.params().size(); i++)
            cls.addField(expressionType(spec.params().get(i)), "expr" + i, Modifier.PRIVATE);
        if (spec.reason())
            cls.addField(ParameterizedTypeName.get(SkriptTypes.EXPRESSION,
                WildcardTypeName.subtypeOf(ClassName.get(String.class))), "exprReason", Modifier.PRIVATE);
        cls.addField(SkriptTypes.NODE, "node", Modifier.PRIVATE);

        cls.addMethod(init(spec));
        cls.addMethod(execute(spec));
        cls.addMethod(toString(spec));

        JavaFile.builder(PKG, cls.build()).build().writeTo(env.getFiler());
        Log.note(env, "Generated " + PKG + "." + spec.className());
    }

    private static List<String> patterns(EffectSpec spec) {
        if (!spec.reason()) return spec.patterns();
        List<String> withReason = new ArrayList<>();
        for (String pattern : spec.patterns())
            withReason.add(pattern + REASON_PATTERN);
        return withReason;
    }

    private static MethodSpec init(EffectSpec spec) {
        MethodSpec.Builder init = MethodSpec.methodBuilder("init")
            .addAnnotation(Override.class)
            .addAnnotation(AnnotationSpec.builder(SuppressWarnings.class)
                .addMember("value", "$S", "unchecked").build())
            .addModifiers(Modifier.PUBLIC)
            .returns(boolean.class)
            .addParameter(ArrayTypeName.of(ParameterizedTypeName.get(SkriptTypes.EXPRESSION,
                WildcardTypeName.subtypeOf(Object.class))), "exprs")
            .addParameter(int.class, "matchedPattern")
            .addParameter(SkriptTypes.KLEENEAN, "isDelayed")
            .addParameter(SkriptTypes.PARSE_RESULT, "parseResult");

        for (int i = 0; i < spec.params().size(); i++)
            init.addStatement("this.expr$L = ($T) exprs[$L]", i, expressionType(spec.params().get(i)), i);
        if (spec.reason())
            init.addStatement("this.exprReason = ($T) exprs[$L]",
                ParameterizedTypeName.get(SkriptTypes.EXPRESSION,
                    WildcardTypeName.subtypeOf(ClassName.get(String.class))), spec.params().size());

        init.addStatement("this.node = getParser().getNode()");
        init.addStatement("getParser().setHasDelayBefore($T.TRUE)", SkriptTypes.KLEENEAN);
        init.addStatement("return true");
        return init.build();
    }

    private static MethodSpec execute(EffectSpec spec) {
        MethodSpec.Builder execute = MethodSpec.methodBuilder("execute")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PROTECTED)
            .returns(void.class)
            .addParameter(SkriptTypes.EVENT, "event");

        List<String> arguments = new ArrayList<>();
        for (int i = 0; i < spec.params().size(); i++) {
            Param param = spec.params().get(i);
            boolean optional = spec.slots().get(i).optional();
            String name = "arg" + i;
            arguments.add(name);

            if (param.array()) {
                execute.addStatement("$T[] $L = this.expr$L == null ? new $T[0] : this.expr$L.getArray(event)",
                    param.element(), name, i, param.element(), i);
                continue;
            }
            execute.addStatement("$T $L = this.expr$L == null ? null : this.expr$L.getSingle(event)",
                param.element(), name, i, i);
            if (!optional) {
                execute.beginControlFlow("if ($L == null)", name)
                    .addStatement("$T.error(new $T($S), this.node, event)", SkriptTypes.DISKY_RUNTIME_HANDLER,
                        IllegalArgumentException.class,
                        "the " + param.name() + " of '" + spec.humanName() + "' is not set")
                    .addStatement("return")
                    .endControlFlow();
            }
        }

        execute.beginControlFlow("try");
        String call = String.join(", ", arguments);
        if (spec.rest()) {
            execute.addStatement("var __action = $T.$L($L)", spec.owner(), spec.method(), call);
            execute.beginControlFlow("if (__action != null)");
            if (spec.reason()) {
                execute.addStatement("$T __reason = this.exprReason == null ? null : this.exprReason.getSingle(event)",
                    String.class);
                execute.addStatement("__action.reason(__reason).complete()");
            } else {
                execute.addStatement("__action.complete()");
            }
            execute.endControlFlow();
        } else {
            execute.addStatement("$T.$L($L)", spec.owner(), spec.method(), call);
        }
        execute.nextControlFlow("catch ($T __ex)", Throwable.class)
            .addStatement("$T.error(__ex, this.node, event)", SkriptTypes.DISKY_RUNTIME_HANDLER)
            .endControlFlow();

        return execute.build();
    }

    private static MethodSpec toString(EffectSpec spec) {
        MethodSpec.Builder toString = MethodSpec.methodBuilder("toString")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(String.class)
            .addParameter(SkriptTypes.EVENT, "event")
            .addParameter(boolean.class, "debug")
            .addStatement("$T sb = new $T($S)", StringBuilder.class, StringBuilder.class, spec.humanName());
        for (int i = 0; i < spec.params().size(); i++)
            toString.addStatement("sb.append(' ').append(this.expr$L == null ? $S : this.expr$L.toString(event, debug))",
                i, "-", i);
        toString.addStatement("return sb.toString()");
        return toString.build();
    }

    private static TypeName expressionType(Param param) {
        return ParameterizedTypeName.get(SkriptTypes.EXPRESSION, WildcardTypeName.subtypeOf(param.element()));
    }

    private static void recordManifest(EffectSpec spec, List<SyntaxRecord> syntaxRecords) {
        Documentation d = spec.docs();
        String docName = (d != null && !d.name().isBlank()) ? d.name() : null;
        List<String> description = d != null ? List.of(d.description()) : List.of();
        List<String> examples    = d != null ? List.of(d.examples())    : List.of();
        String since = Versions.first(d == null ? null : d.since());
        syntaxRecords.add(new SyntaxRecord(
            spec.subjectEntity(), spec.humanName(), "EFFECT", null, false,
            List.of(), false, spec.rest(), false, false, false,
            docName, description, examples, since, patterns(spec)));
    }
}
