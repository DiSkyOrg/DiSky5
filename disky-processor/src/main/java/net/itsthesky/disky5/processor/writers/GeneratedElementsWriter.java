package net.itsthesky.disky5.processor.writers;

import com.squareup.javapoet.*;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.util.List;

/** Each generated Prop... class self-registers in a static{} block; Class.forName(fqn, true, loader) is what triggers that - a bare Foo.class literal would only load it, not initialize it. */
public final class GeneratedElementsWriter {

    public static final String PACKAGE = "net.itsthesky.disky5.generated";
    public static final String CLASS_NAME = "GeneratedElements";

    public static void write(ProcessingEnvironment env, List<String> generatedClassFqns) throws IOException {
        MethodSpec.Builder registerAll = MethodSpec.methodBuilder("registerAll")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .addJavadoc("Force-loads (and thereby initializes) every generated syntax class so its\n"
                + "static {@code register(...)} block runs. Must be called inside a Skript\n"
                + "registration window (see DiSky5#onEnable).\n")
            .addStatement("$T loader = $L.class.getClassLoader()",
                ClassName.get(ClassLoader.class), CLASS_NAME);

        for (String fqn : generatedClassFqns) {
            registerAll
                .beginControlFlow("try")
                .addStatement("$T.forName($S, true, loader)", ClassName.get(Class.class), fqn)
                .nextControlFlow("catch ($T ex)", ClassName.get(Throwable.class))
                .addStatement("$T.getLogger($S).log($T.SEVERE, $S, ex)",
                    ClassName.get("java.util.logging", "Logger"), "DiSky",
                    ClassName.get("java.util.logging", "Level"),
                    "[DiSky] a generated syntax class failed to register: " + fqn)
                .endControlFlow();
        }

        TypeSpec cls = TypeSpec.classBuilder(CLASS_NAME)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build())
            .addMethod(registerAll.build())
            .build();

        JavaFile.builder(PACKAGE, cls).build().writeTo(env.getFiler());
    }
}
