package net.itsthesky.disky5.processor.writers;

import com.squareup.javapoet.JavaFile;
import com.squareup.javapoet.MethodSpec;
import com.squareup.javapoet.ParameterizedTypeName;
import com.squareup.javapoet.TypeSpec;
import net.itsthesky.disky5.processor.DiSkyProcessor;
import net.itsthesky.disky5.processor.util.SkriptTypes;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.util.List;

public final class TypeRegistryWriter {

    public static void write(ProcessingEnvironment env, List<DiSkyProcessor.TypeInfo> types) throws IOException {
        MethodSpec.Builder register = MethodSpec.methodBuilder("register")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC);

        for (DiSkyProcessor.TypeInfo t : types) {
            TypeSpec parser = TypeSpec.anonymousClassBuilder("")
                .addSuperinterface(ParameterizedTypeName.get(SkriptTypes.PARSER, t.jdaType()))
                .addMethod(MethodSpec.methodBuilder("canParse")
                    .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
                    .returns(boolean.class)
                    .addParameter(SkriptTypes.PARSE_CONTEXT, "context")
                    .addStatement("return false").build())
                .addMethod(MethodSpec.methodBuilder("toString")
                    .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
                    .returns(String.class)
                    .addParameter(t.jdaType(), "o").addParameter(int.class, "flags")
                    .addStatement("return $T.display(o)", SkriptTypes.CONVERSIONS).build())
                .addMethod(MethodSpec.methodBuilder("toVariableNameString")
                    .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
                    .returns(String.class)
                    .addParameter(t.jdaType(), "o")
                    .addStatement("return $S + o", t.codeName() + ":").build())
                .build();

            register
                .beginControlFlow("if ($T.getExactClassInfo($T.class) == null)",
                        SkriptTypes.CLASSES, t.jdaType())
                .addStatement(
                    "$T.registerClass(new $T<>($T.class, $S).user($S).name($S).parser($L))",
                    SkriptTypes.CLASSES, SkriptTypes.CLASS_INFO, t.jdaType(),
                    t.codeName(), t.userPattern(), t.displayName(), parser)
                .endControlFlow();
        }

        TypeSpec cls = TypeSpec.classBuilder("GeneratedTypes")
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build())
            .addMethod(register.build())
            .build();

        JavaFile.builder("net.itsthesky.disky5.generated", cls).build().writeTo(env.getFiler());
    }
}