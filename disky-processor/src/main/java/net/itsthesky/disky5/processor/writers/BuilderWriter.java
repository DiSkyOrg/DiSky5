import net.itsthesky.disky5.processor.util.Versions;
import com.squareup.javapoet.*;
import net.itsthesky.disky5.annotations.docs.Documentation;
import net.itsthesky.disky5.processor.DiSkyProcessor.SyntaxRecord;
import net.itsthesky.disky5.processor.handlers.BuilderHandler.BuildSpec;
import net.itsthesky.disky5.processor.handlers.BuilderHandler.NewSpec;
import net.itsthesky.disky5.processor.handlers.EffectHandler.Param;
import net.itsthesky.disky5.processor.util.DocsUtils;
import net.itsthesky.disky5.processor.util.Log;
import net.itsthesky.disky5.processor.util.SkriptTypes;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.util.ArrayList;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

public final class BuilderWriter {

    private BuilderWriter() {}

    private static String packageOf(ClassName owner) {
        return owner.packageName().replace("descriptors", "generated");
    }

    private static final String UNION_PACKAGE = "net.itsthesky.disky5.generated.builders";
    private static final String UNION_CLASS = "BuildExpr_Union";

    public static void write(ProcessingEnvironment env, Collection<NewSpec> factories,
                             Collection<BuildSpec> builds, Map<String, String> codeNameByJdaFqn,
                             List<String> generatedClasses, List<SyntaxRecord> syntaxRecords)
            throws IOException {
        for (NewSpec spec : factories) {
            writeFactory(env, spec);
            generatedClasses.add(packageOf(spec.owner()) + "." + spec.className());
            record(syntaxRecords, codeNameByJdaFqn.get(spec.builderType().toString()), spec.humanName(),
                spec.patterns(), spec.builderType().toString(), spec.docs(), false);
        }
        List<BuildSpec> buildList = new ArrayList<>(builds);
        if (buildList.size() > 1) {
            writeUnionBuild(env, buildList, codeNameByJdaFqn);
            generatedClasses.add(UNION_PACKAGE + "." + UNION_CLASS);
        }
        for (BuildSpec spec : buildList) {
            String resultCodeName = codeNameByJdaFqn.get(spec.resultFqn());
            if (buildList.size() == 1) {
                writeBuild(env, spec, resultCodeName);
                generatedClasses.add(packageOf(spec.owner()) + "." + spec.className());
            }
            record(syntaxRecords, spec.builderCodeName(), "result", spec.patterns(resultCodeName),
                spec.resultFqn(), spec.docs(), true);
        }
    }

    private static void writeFactory(ProcessingEnvironment env, NewSpec spec) throws IOException {
        ClassName builder = spec.builderType();

        TypeSpec.Builder cls = TypeSpec.classBuilder(spec.className())
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .superclass(ParameterizedTypeName.get(SkriptTypes.SIMPLE_EXPRESSION, builder));

        DocsUtils.attachDocumentation(cls, spec.docs());

        CodeBlock.Builder reg = CodeBlock.builder()
            .add("$T.registerExpression($L.class, $T.class, $T.COMBINED", SkriptTypes.SKRIPT,
                spec.className(), builder, SkriptTypes.EXPRESSION_TYPE);
        for (String pattern : spec.patterns())
            reg.add(",\n$S", pattern);
        reg.add(");\n");
        cls.addStaticBlock(reg.build());

        for (int i = 0; i < spec.params().size(); i++)
            cls.addField(expressionType(spec.params().get(i)), "expr" + i, Modifier.PRIVATE);
        cls.addField(SkriptTypes.NODE, "node", Modifier.PRIVATE);

        MethodSpec.Builder init = initBuilder();
        for (int i = 0; i < spec.params().size(); i++)
            init.addStatement("this.expr$L = ($T) exprs[$L]", i, expressionType(spec.params().get(i)), i);
        init.addStatement("this.node = getParser().getNode()");
        init.addStatement("return true");
        cls.addMethod(init.build());

        MethodSpec.Builder get = MethodSpec.methodBuilder("get")
            .addAnnotation(Override.class).addModifiers(Modifier.PROTECTED)
            .returns(ArrayTypeName.of(builder))
            .addParameter(SkriptTypes.EVENT, "event");

        List<String> arguments = new ArrayList<>();
        for (int i = 0; i < spec.params().size(); i++) {
            Param param = spec.params().get(i);
            String name = "arg" + i;
            arguments.add(name);
            if (param.array()) {
                get.addStatement("$T[] $L = this.expr$L == null ? new $T[0] : this.expr$L.getArray(event)",
                    param.element(), name, i, param.element(), i);
                continue;
            }
            get.addStatement("$T $L = this.expr$L == null ? null : this.expr$L.getSingle(event)",
                param.element(), name, i, i);
            if (!spec.slots().get(i).optional())
                get.beginControlFlow("if ($L == null)", name)
                    .addStatement("return new $T[0]", builder)
                    .endControlFlow();
        }

        get.beginControlFlow("try")
            .addStatement("return new $T[]{ $T.$L($L) }", builder, spec.owner(), spec.method(),
                String.join(", ", arguments))
            .nextControlFlow("catch ($T __ex)", Throwable.class)
            .addStatement("$T.error(__ex, this.node, event)", SkriptTypes.DISKY_RUNTIME_HANDLER)
            .addStatement("return new $T[0]", builder)
            .endControlFlow();
        cls.addMethod(get.build());

        addTail(cls, builder, spec.humanName());
        emit(env, cls.build(), packageOf(spec.owner()), spec.className());
    }

    private static void writeBuild(ProcessingEnvironment env, BuildSpec spec, String resultCodeName)
            throws IOException {
        ClassName result = ClassName.bestGuess(spec.resultFqn());

        TypeSpec.Builder cls = TypeSpec.classBuilder(spec.className())
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .superclass(ParameterizedTypeName.get(SkriptTypes.SIMPLE_EXPRESSION, result));

        DocsUtils.attachDocumentation(cls, spec.docs());

        CodeBlock.Builder reg = CodeBlock.builder()
            .add("$T.registerExpression($L.class, $T.class, $T.COMBINED", SkriptTypes.SKRIPT,
                spec.className(), result, SkriptTypes.EXPRESSION_TYPE);
        for (String pattern : spec.patterns(resultCodeName))
            reg.add(",\n$S", pattern);
        reg.add(");\n");
        cls.addStaticBlock(reg.build());

        TypeName sourceType = ParameterizedTypeName.get(SkriptTypes.EXPRESSION,
            WildcardTypeName.subtypeOf(spec.builderType()));
        cls.addField(sourceType, "source", Modifier.PRIVATE);
        cls.addField(SkriptTypes.NODE, "node", Modifier.PRIVATE);

        String subject = resultCodeName == null ? "this builder" : "a " + resultCodeName;
        MethodSpec.Builder init = initBuilder()
            .beginControlFlow("if (!$T.isParsingInsideAwait())", SkriptTypes.DISKY_ASYNC)
            .addStatement("$T.error($S)", SkriptTypes.SKRIPT,
                "creating " + subject + " talks to Discord, so this requires 'await'")
            .addStatement("return false")
            .endControlFlow()
            .addStatement("this.source = ($T) exprs[0]", sourceType)
            .addStatement("this.node = getParser().getNode()")
            .addStatement("return true");
        cls.addMethod(init.build());

        MethodSpec.Builder get = MethodSpec.methodBuilder("get")
            .addAnnotation(Override.class).addModifiers(Modifier.PROTECTED)
            .returns(ArrayTypeName.of(result))
            .addParameter(SkriptTypes.EVENT, "event")
            .addStatement("$T builder = this.source == null ? null : this.source.getSingle(event)",
                spec.builderType())
            .beginControlFlow("if (builder == null)")
            .addStatement("return new $T[0]", result)
            .endControlFlow()
            .beginControlFlow("try");
        if (spec.rest())
            get.addStatement("return new $T[]{ $T.$L(builder).complete() }", result, spec.owner(), spec.method());
        else
            get.addStatement("return new $T[]{ $T.$L(builder) }", result, spec.owner(), spec.method());
        get.nextControlFlow("catch ($T __ex)", Throwable.class)
            .addStatement("$T.error(__ex, this.node, event)", SkriptTypes.DISKY_RUNTIME_HANDLER)
            .addStatement("return new $T[0]", result)
            .endControlFlow();
        cls.addMethod(get.build());

        addTail(cls, result, "the result of the " + spec.builderCodeName());
        emit(env, cls.build(), packageOf(spec.owner()), spec.className());
    }

    private static void writeUnionBuild(ProcessingEnvironment env, List<BuildSpec> specs,
                                        Map<String, String> codeNameByJdaFqn) throws IOException {
        ClassName object = ClassName.get(Object.class);

        List<String> builderCodes = new ArrayList<>();
        for (BuildSpec spec : specs) builderCodes.add(spec.builderCodeName());
        String slot = "%" + String.join("/", builderCodes) + "%";

        Map<String, List<String>> buildersByResult = new LinkedHashMap<>();
        for (BuildSpec spec : specs) {
            String resultCode = codeNameByJdaFqn.get(spec.resultFqn());
            if (resultCode != null)
                buildersByResult.computeIfAbsent(resultCode, k -> new ArrayList<>()).add(spec.builderCodeName());
        }

        List<String> patterns = new ArrayList<>();
        patterns.add("[the] (build|built) result of [the] " + slot);
        for (Map.Entry<String, List<String>> entry : buildersByResult.entrySet())
            patterns.add("[the] built " + entry.getKey() + " [from] [the] %"
                + String.join("/", entry.getValue()) + "%");

        TypeSpec.Builder cls = TypeSpec.classBuilder(UNION_CLASS)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n"
                + "Builds $L, dispatched by runtime type.\n", slot)
            .superclass(ParameterizedTypeName.get(SkriptTypes.SIMPLE_EXPRESSION, object));

        CodeBlock.Builder reg = CodeBlock.builder()
            .add("$T.registerExpression($L.class, $T.class, $T.COMBINED", SkriptTypes.SKRIPT,
                UNION_CLASS, object, SkriptTypes.EXPRESSION_TYPE);
        for (String pattern : patterns)
            reg.add(",\n$S", pattern);
        reg.add(");\n");
        cls.addStaticBlock(reg.build());

        TypeName sourceType = ParameterizedTypeName.get(SkriptTypes.EXPRESSION,
            WildcardTypeName.subtypeOf(Object.class));
        cls.addField(sourceType, "source", Modifier.PRIVATE);
        cls.addField(SkriptTypes.NODE, "node", Modifier.PRIVATE);
        cls.addField(ParameterizedTypeName.get(ClassName.get(Class.class),
            WildcardTypeName.subtypeOf(Object.class)), "resultType", Modifier.PRIVATE);

        MethodSpec.Builder init = initBuilder()
            .beginControlFlow("if (!$T.isParsingInsideAwait())", SkriptTypes.DISKY_ASYNC)
            .addStatement("$T.error($S)", SkriptTypes.SKRIPT,
                "building talks to Discord, so this requires 'await'")
            .addStatement("return false")
            .endControlFlow()
            .addStatement("this.source = exprs[0]")
            .addStatement("this.node = getParser().getNode()")
            .addStatement("$T<?> __source = this.source.getReturnType()", ClassName.get(Class.class))
            .addStatement("this.resultType = $T.class", object);
        for (BuildSpec spec : specs)
            init.beginControlFlow("if ($T.class.isAssignableFrom(__source))", spec.builderType())
                .addStatement("this.resultType = $T.class", ClassName.bestGuess(spec.resultFqn()))
                .endControlFlow();
        init.addStatement("return true");
        cls.addMethod(init.build());

        MethodSpec.Builder get = MethodSpec.methodBuilder("get")
            .addAnnotation(Override.class).addModifiers(Modifier.PROTECTED)
            .returns(ArrayTypeName.of(object))
            .addParameter(SkriptTypes.EVENT, "event")
            .addStatement("$T builder = this.source == null ? null : this.source.getSingle(event)", object)
            .beginControlFlow("if (builder == null)")
            .addStatement("return new $T[0]", object)
            .endControlFlow()
            .beginControlFlow("try");
        for (BuildSpec spec : specs) {
            get.beginControlFlow("if (builder instanceof $T __b)", spec.builderType());
            if (spec.rest())
                get.addStatement("return new $T[]{ $T.$L(__b).complete() }", object, spec.owner(), spec.method());
            else
                get.addStatement("return new $T[]{ $T.$L(__b) }", object, spec.owner(), spec.method());
            get.endControlFlow();
        }
        get.nextControlFlow("catch ($T __ex)", Throwable.class)
            .addStatement("$T.error(__ex, this.node, event)", SkriptTypes.DISKY_RUNTIME_HANDLER)
            .endControlFlow()
            .addStatement("return new $T[0]", object);
        cls.addMethod(get.build());

        cls.addMethod(MethodSpec.methodBuilder("isSingle")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(boolean.class).addStatement("return true").build());
        cls.addMethod(MethodSpec.methodBuilder("getReturnType")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(ParameterizedTypeName.get(ClassName.get(Class.class),
                WildcardTypeName.subtypeOf(Object.class)))
            .addStatement("return this.resultType == null ? $T.class : this.resultType", object).build());
        cls.addMethod(MethodSpec.methodBuilder("toString")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(String.class)
            .addParameter(SkriptTypes.EVENT, "event").addParameter(boolean.class, "debug")
            .addStatement("return $S", "the result of the builder").build());

        emit(env, cls.build(), UNION_PACKAGE, UNION_CLASS);
    }

    private static MethodSpec.Builder initBuilder() {
        return MethodSpec.methodBuilder("init")
            .addAnnotation(Override.class)
            .addAnnotation(AnnotationSpec.builder(SuppressWarnings.class)
                .addMember("value", "$S", "unchecked").build())
            .addModifiers(Modifier.PUBLIC)
            .returns(boolean.class)
            .addParameter(ArrayTypeName.of(ParameterizedTypeName.get(SkriptTypes.EXPRESSION,
                WildcardTypeName.subtypeOf(Object.class))), "exprs")
            .addParameter(int.class, "matchedPattern")
            .addParameter(SkriptTypes.KLEENEAN, "isDelayed")
            .addParameter(SkriptTypes.PARSE_RESULT, "parseResult");
    }

    private static void addTail(TypeSpec.Builder cls, ClassName returnClass, String label) {
        cls.addMethod(MethodSpec.methodBuilder("isSingle")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(boolean.class).addStatement("return true").build());
        cls.addMethod(MethodSpec.methodBuilder("getReturnType")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(ParameterizedTypeName.get(ClassName.get(Class.class), returnClass))
            .addStatement("return $T.class", returnClass).build());
        cls.addMethod(MethodSpec.methodBuilder("toString")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(String.class)
            .addParameter(SkriptTypes.EVENT, "event").addParameter(boolean.class, "debug")
            .addStatement("return $S", label).build());
    }

    private static TypeName expressionType(Param param) {
        return ParameterizedTypeName.get(SkriptTypes.EXPRESSION, WildcardTypeName.subtypeOf(param.element()));
    }

    private static void emit(ProcessingEnvironment env, TypeSpec cls, String pkg, String className)
            throws IOException {
        JavaFile.builder(pkg, cls).build().writeTo(env.getFiler());
        Log.note(env, "Generated " + pkg + "." + className);
    }

    private static void record(List<SyntaxRecord> syntaxRecords, String entityId, String name,
                               List<String> patterns, String returnFqn, Documentation d, boolean awaitOnly) {
        String docName = (d != null && !d.name().isBlank()) ? d.name() : null;
        List<String> description = d != null ? List.of(d.description()) : List.of();
        List<String> examples    = d != null ? List.of(d.examples())    : List.of();
        String since = Versions.first(d == null ? null : d.since());
        syntaxRecords.add(new SyntaxRecord(
            entityId, name, "EXPRESSION", returnFqn, false,
            List.of(), awaitOnly, awaitOnly, awaitOnly, false, false,
            docName, description, examples, since, patterns));
    }
}
