package net.itsthesky.disky5.processor.writers;

import net.itsthesky.disky5.processor.util.Versions;
import com.squareup.javapoet.*;
import net.itsthesky.disky5.annotations.Condition;
import net.itsthesky.disky5.annotations.docs.Documentation;
import net.itsthesky.disky5.processor.DescriptorContext;
import net.itsthesky.disky5.processor.DiSkyProcessor;
import net.itsthesky.disky5.processor.util.DocsUtils;
import net.itsthesky.disky5.processor.util.NameUtils;
import net.itsthesky.disky5.processor.util.SkriptTypes;
import net.itsthesky.disky5.processor.util.TypeUtils;
import net.itsthesky.disky5.processor.util.Log;

import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.VariableElement;
import javax.tools.Diagnostic;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;

public final class ConditionWriter {

    private ConditionWriter() {}

    public static void write(DescriptorContext ctx, ExecutableElement method, Condition cond) throws IOException {
        if (cond.patterns().length == 0)
            writePropertyCondition(ctx, method, cond);
        else
            writeFullCondition(ctx, method, cond);
    }

    private static String className(DescriptorContext ctx, ExecutableElement method) {
        return "Cond" + NameUtils.entityName(ctx.descriptorFqn)
            + NameUtils.toClassName(splitCamel(method.getSimpleName().toString()));
    }

    private static String splitCamel(String name) {
        return name.replaceAll("([a-z0-9])([A-Z])", "$1 $2").toLowerCase();
    }

    private static void writePropertyCondition(DescriptorContext ctx, ExecutableElement method,
                                               Condition cond) throws IOException {
        List<? extends VariableElement> params = method.getParameters();
        String subjectType = TypeUtils.stripAnnotations(params.get(0).asType().toString());
        ClassName subjectClass = ClassName.bestGuess(TypeUtils.boxed(subjectType));
        ClassName descriptorClass = ClassName.bestGuess(ctx.descriptorFqn);

        String name = className(ctx, method);
        String property = cond.property();
        String pluralUser = ctx.codeName + "s";
        String propertyType = cond.type().name();

        TypeSpec.Builder cls = TypeSpec.classBuilder(name)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .superclass(ParameterizedTypeName.get(SkriptTypes.PROPERTY_CONDITION, subjectClass));

        DocsUtils.attachDocumentation(cls, method.getAnnotation(Documentation.class));

        cls.addStaticBlock(CodeBlock.of(
            "$T.register($L.class, $T.$L, $S, $S);\n",
            SkriptTypes.PROPERTY_CONDITION, name, SkriptTypes.PROPERTY_TYPE, propertyType, property, pluralUser));

        cls.addMethod(MethodSpec.methodBuilder("check")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(boolean.class)
            .addParameter(subjectClass, "value")
            .addStatement("return $T.$L(value)", descriptorClass, method.getSimpleName())
            .build());

        cls.addMethod(MethodSpec.methodBuilder("getPropertyName")
            .addAnnotation(Override.class).addModifiers(Modifier.PROTECTED)
            .returns(String.class)
            .addStatement("return $S", property)
            .build());

        cls.addMethod(MethodSpec.methodBuilder("getPropertyType")
            .addAnnotation(Override.class).addModifiers(Modifier.PROTECTED)
            .returns(SkriptTypes.PROPERTY_TYPE)
            .addStatement("return $T.$L", SkriptTypes.PROPERTY_TYPE, propertyType)
            .build());

        emit(ctx, cls.build(), name);
        recordManifest(ctx, method, property,
            List.of("%" + pluralUser + "% " + verb(cond) + " " + property));
    }

    private static void writeFullCondition(DescriptorContext ctx, ExecutableElement method,
                                           Condition cond) throws IOException {
        List<? extends VariableElement> params = method.getParameters();
        ClassName descriptorClass = ClassName.bestGuess(ctx.descriptorFqn);
        String name = className(ctx, method);

        List<ParamInfo> infos = new ArrayList<>();
        for (VariableElement p : params) {
            String raw = TypeUtils.paramType(p.asType().toString());
            boolean array = TypeUtils.isArray(raw);
            String element = TypeUtils.boxed(TypeUtils.arrayComponent(raw));
            infos.add(new ParamInfo(ClassName.bestGuess(element), array, p.getSimpleName().toString()));
        }

        TypeSpec.Builder cls = TypeSpec.classBuilder(name)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .superclass(SkriptTypes.CONDITION);

        DocsUtils.attachDocumentation(cls, method.getAnnotation(Documentation.class));

        CodeBlock.Builder reg = CodeBlock.builder().add("$T.registerCondition($L.class", SkriptTypes.SKRIPT, name);
        for (String pattern : cond.patterns())
            reg.add(",\n$S", pattern);
        reg.add(");\n");
        cls.addStaticBlock(reg.build());

        for (int i = 0; i < infos.size(); i++)
            cls.addField(ParameterizedTypeName.get(SkriptTypes.EXPRESSION,
                WildcardTypeName.subtypeOf(infos.get(i).element)), "expr" + i, Modifier.PRIVATE);

        MethodSpec.Builder init = MethodSpec.methodBuilder("init")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(boolean.class)
            .addParameter(ArrayTypeName.of(ParameterizedTypeName.get(SkriptTypes.EXPRESSION,
                WildcardTypeName.subtypeOf(Object.class))), "exprs")
            .addParameter(int.class, "matchedPattern")
            .addParameter(SkriptTypes.KLEENEAN, "isDelayed")
            .addParameter(SkriptTypes.PARSE_RESULT, "parseResult")
            .addAnnotation(suppressUnchecked());
        for (int i = 0; i < infos.size(); i++)
            init.addStatement("this.expr$L = ($T) exprs[$L]", i,
                ParameterizedTypeName.get(SkriptTypes.EXPRESSION, WildcardTypeName.subtypeOf(infos.get(i).element)), i);
        init.addStatement("setNegated($L)", negatedExpr(cond.negated()));
        init.addStatement("return true");
        cls.addMethod(init.build());

        MethodSpec.Builder check = MethodSpec.methodBuilder("check")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(boolean.class)
            .addParameter(SkriptTypes.EVENT, "event");
        StringBuilder call = new StringBuilder("$T.$L(subject");
        List<Object> callArgs = new ArrayList<>();
        callArgs.add(descriptorClass);
        callArgs.add(method.getSimpleName().toString());
        for (int i = 1; i < infos.size(); i++) {
            ParamInfo info = infos.get(i);
            if (info.array) {
                check.addStatement("$T[] arg$L = this.expr$L == null ? new $T[0] : this.expr$L.getArray(event)",
                    info.element, i, i, info.element, i);
            } else {
                check.addStatement("$T arg$L = this.expr$L == null ? null : this.expr$L.getSingle(event)",
                    info.element, i, i, i);
            }
            call.append(", arg").append(i);
        }
        call.append(")");
        check.addStatement("return this.expr0.check(event, subject -> " + call + ", isNegated())",
            callArgs.toArray());
        cls.addMethod(check.build());

        cls.addMethod(MethodSpec.methodBuilder("toString")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(String.class)
            .addParameter(SkriptTypes.EVENT, "event")
            .addParameter(boolean.class, "debug")
            .addStatement("return $S", name)
            .build());

        emit(ctx, cls.build(), name);
        recordManifest(ctx, method, splitCamel(method.getSimpleName().toString()), shownPatterns(cond));
    }

    private static List<String> shownPatterns(Condition cond) {
        List<String> shown = new ArrayList<>();
        outer:
        for (int i = 0; i < cond.patterns().length; i++) {
            for (int n : cond.negated()) if (n == i) continue outer;
            shown.add(cond.patterns()[i]);
        }
        return shown;
    }

    private static String verb(Condition cond) {
        return switch (cond.type()) {
            case CAN -> "can";
            case HAVE -> "(has|have)";
            default -> "(is|are)";
        };
    }

    private static void recordManifest(DescriptorContext ctx, ExecutableElement method,
                                       String displayName, List<String> patterns) {
        Documentation d = method.getAnnotation(Documentation.class);
        String docName = (d != null && !d.name().isBlank()) ? d.name() : null;
        List<String> description = d != null ? List.of(d.description()) : List.of();
        List<String> examples    = d != null ? List.of(d.examples())    : List.of();
        String since = Versions.first(d == null ? null : d.since());
        ctx.syntaxRecords.add(new DiSkyProcessor.SyntaxRecord(
            ctx.codeName, displayName, "CONDITION", null, false,
            List.of(), false, false, false, false, false,
            docName, description, examples, since, patterns));
    }

    private static String negatedExpr(int[] negated) {
        if (negated.length == 0) return "false";
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < negated.length; i++) {
            if (i > 0) sb.append(" || ");
            sb.append("matchedPattern == ").append(negated[i]);
        }
        return sb.toString();
    }

    private static AnnotationSpec suppressUnchecked() {
        return AnnotationSpec.builder(SuppressWarnings.class).addMember("value", "$S", "unchecked").build();
    }

    private static void emit(DescriptorContext ctx, TypeSpec cls, String name) throws IOException {
        JavaFile.builder(ctx.generatedPkg, cls).build().writeTo(ctx.env.getFiler());
        ctx.generatedClasses.add(ctx.generatedPkg + "." + name);
        Log.note(ctx.env, "Generated " + ctx.generatedPkg + "." + name);
    }

    private record ParamInfo(ClassName element, boolean array, String name) {}
}
