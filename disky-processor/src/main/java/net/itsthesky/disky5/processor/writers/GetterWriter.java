package net.itsthesky.disky5.processor.writers;

import net.itsthesky.disky5.processor.util.Versions;
import com.squareup.javapoet.*;
import net.itsthesky.disky5.annotations.docs.Documentation;
import net.itsthesky.disky5.processor.DiSkyProcessor.SyntaxRecord;
import net.itsthesky.disky5.processor.handlers.GetterHandler.GetterSpec;
import net.itsthesky.disky5.processor.handlers.GetterHandler.Scope;
import net.itsthesky.disky5.processor.util.DocsUtils;
import net.itsthesky.disky5.processor.util.NameUtils;
import net.itsthesky.disky5.processor.util.SkriptTypes;
import net.itsthesky.disky5.processor.util.TypeUtils;
import net.itsthesky.disky5.processor.util.Log;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Modifier;
import javax.tools.Diagnostic;
import java.io.IOException;
import java.util.Collection;
import java.util.List;
import java.util.Map;

public final class GetterWriter {

    private GetterWriter() {}

    private static final String PKG = "net.itsthesky.disky5.generated";

    public static void write(ProcessingEnvironment env, Collection<GetterSpec> specs,
                             List<String> generatedClasses, List<SyntaxRecord> syntaxRecords,
                             Map<String, String> entityIdByJdaFqn) throws IOException {
        for (GetterSpec spec : specs) {
            String className = "GetterExpr_" + NameUtils.toClassName(spec.name);
            writeGetterClass(env, spec, className);
            generatedClasses.add(PKG + "." + className);
            recordManifest(spec, syntaxRecords, entityIdByJdaFqn);
        }
    }

    private static void recordManifest(GetterSpec spec, List<SyntaxRecord> syntaxRecords,
                                       Map<String, String> entityIdByJdaFqn) {
        String raw = spec.returnType != null && spec.returnType.contains("<")
            ? spec.returnType.substring(0, spec.returnType.indexOf('<')) : spec.returnType;
        String entityId = entityIdByJdaFqn.get(raw);
        if (entityId == null) return;

        String pattern = spec.name + " with id %string%" + scopePattern(spec.scope).patternSuffix;
        Documentation d = spec.docs;
        String docName = (d != null && !d.name().isBlank()) ? d.name() : null;
        List<String> description = d != null ? List.of(d.description()) : List.of();
        List<String> examples    = d != null ? List.of(d.examples())    : List.of();
        String since = Versions.first(d == null ? null : d.since());
        syntaxRecords.add(new SyntaxRecord(
            entityId, spec.name + " with id", "GETTER", spec.returnType, false,
            List.of(), spec.retrieveMethod != null, false, spec.cacheMethod == null, false, false,
            docName, description, examples, since, List.of(pattern)));
    }

    private static void writeGetterClass(ProcessingEnvironment env, GetterSpec spec, String className)
            throws IOException {

        ClassName returnClass = ClassName.bestGuess(TypeUtils.boxed(spec.returnType));
        ClassName holderClass = ClassName.bestGuess(spec.holderFqn);
        boolean retrieveOnly = spec.cacheMethod == null;

        TypeSpec.Builder cls = TypeSpec.classBuilder(className)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .superclass(ParameterizedTypeName.get(SkriptTypes.SIMPLE_EXPRESSION, returnClass));

        DocsUtils.attachDocumentation(cls, spec.docs);

        TypeName idExprType = ParameterizedTypeName.get(SkriptTypes.EXPRESSION, ClassName.get(String.class));
        cls.addField(idExprType, "idExpr", Modifier.PRIVATE);

        ScopePattern scope = scopePattern(spec.scope);
        TypeName scopeExprType = ParameterizedTypeName.get(SkriptTypes.EXPRESSION, scope.scopeClass);
        cls.addField(scopeExprType, "scopeExpr", Modifier.PRIVATE);

        cls.addStaticBlock(CodeBlock.of(
            "$T.registerExpression($L.class, $T.class, $T.COMBINED, $S);\n",
            SkriptTypes.SKRIPT, className, returnClass, SkriptTypes.EXPRESSION_TYPE,
            spec.name + " with id %string%" + scope.patternSuffix));

        MethodSpec.Builder init = MethodSpec.methodBuilder("init")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(boolean.class)
            .addParameter(ArrayTypeName.of(WildcardExpression()), "exprs")
            .addParameter(int.class, "matchedPattern")
            .addParameter(SkriptTypes.KLEENEAN, "isDelayed")
            .addParameter(SkriptTypes.PARSE_RESULT, "parseResult");

        if (retrieveOnly) {
            init.beginControlFlow("if (!$T.isParsingInsideAwait())", SkriptTypes.DISKY_ASYNC)
                .addStatement("$T.error($S)", SkriptTypes.SKRIPT,
                    "the '" + spec.name + " with id' getter is online-only and requires 'await'")
                .addStatement("return false")
                .endControlFlow();
        }

        init.addStatement("this.idExpr = ($T) exprs[0]", idExprType);
        init.addStatement("this.scopeExpr = ($T) exprs[1]", scopeExprType);
        init.addStatement("return true");
        cls.addMethod(init.build());

        cls.addMethod(buildGet(spec, returnClass, holderClass, scope));

        cls.addMethod(MethodSpec.methodBuilder("empty")
            .addModifiers(Modifier.PRIVATE)
            .returns(ArrayTypeName.of(returnClass))
            .addStatement("return ($T[]) $T.newInstance($T.class, 0)",
                returnClass, java.lang.reflect.Array.class, returnClass)
            .build());

        cls.addMethod(MethodSpec.methodBuilder("wrap")
            .addModifiers(Modifier.PRIVATE)
            .returns(ArrayTypeName.of(returnClass))
            .addParameter(returnClass, "value")
            .addStatement("$T[] out = ($T[]) $T.newInstance($T.class, 1)",
                returnClass, returnClass, java.lang.reflect.Array.class, returnClass)
            .addStatement("out[0] = value")
            .addStatement("return out")
            .build());

        cls.addMethod(MethodSpec.methodBuilder("isSingle")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(boolean.class).addStatement("return true").build());

        cls.addMethod(MethodSpec.methodBuilder("getReturnType")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(ParameterizedTypeName.get(ClassName.get(Class.class), returnClass))
            .addStatement("return $T.class", returnClass).build());

        cls.addMethod(MethodSpec.methodBuilder("toString")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(String.class)
            .addParameter(SkriptTypes.EVENT, "event").addParameter(boolean.class, "debug")
            .addStatement("return $S", spec.name + " with id")
            .build());

        JavaFile.builder(PKG, cls.build()).build().writeTo(env.getFiler());
        Log.note(env, "Generated " + PKG + "." + className);
    }

    private static MethodSpec buildGet(GetterSpec spec, ClassName returnClass,
                                       ClassName holderClass, ScopePattern scope) {
        boolean hasCache = spec.cacheMethod != null;
        boolean hasRetrieve = spec.retrieveMethod != null;

        MethodSpec.Builder get = MethodSpec.methodBuilder("get")
            .addAnnotation(Override.class).addModifiers(Modifier.PROTECTED)
            .returns(ArrayTypeName.of(returnClass))
            .addParameter(SkriptTypes.EVENT, "event");

        get.addStatement("$T id = idExpr.getSingle(event)", String.class);
        get.beginControlFlow("if (id == null)")
            .addStatement("return empty()")
            .endControlFlow();

        if (scope.scope == Scope.BOT) {
            get.addStatement("$T bot = scopeExpr == null ? null : scopeExpr.getSingle(event)", SkriptTypes.BOT);
            get.beginControlFlow("if (bot == null)")
                .addStatement("bot = $T.getBots().findAny()", SkriptTypes.DISKY5)
                .endControlFlow();
            get.beginControlFlow("if (bot == null)")
                .addStatement("return empty()")
                .endControlFlow();
            get.addStatement("$T scope = bot.getShardManager()", SkriptTypes.SHARD_MANAGER);
            get.beginControlFlow("if (scope == null)")
                .addStatement("return empty()")
                .endControlFlow();
        } else {
            get.addStatement("$T scope = scopeExpr.getSingle(event)", scope.scopeClass);
            get.beginControlFlow("if (scope == null)")
                .addStatement("return empty()")
                .endControlFlow();
        }

        get.addStatement("$T result = null", returnClass);

        if (hasRetrieve) {
            get.beginControlFlow("if ($T.isAwaited(event))", SkriptTypes.DISKY_ASYNC);
            get.beginControlFlow("try");
            if (hasCache) {
                get.addStatement("result = $T.$L(scope, id)", holderClass, spec.cacheMethod);
                get.beginControlFlow("if (result == null)");
                emitRetrieve(get, spec, holderClass);
                get.endControlFlow();
            } else {
                emitRetrieve(get, spec, holderClass);
            }
            get.nextControlFlow("catch ($T error)", Throwable.class)
                .addStatement("$T.error(error, null, event)", SkriptTypes.DISKY_RUNTIME_HANDLER)
                .addStatement("return empty()")
                .endControlFlow();
            if (hasCache) {
                get.nextControlFlow("else");
                get.addStatement("result = $T.$L(scope, id)", holderClass, spec.cacheMethod);
            }
            get.endControlFlow();
        } else {
            get.addStatement("result = $T.$L(scope, id)", holderClass, spec.cacheMethod);
        }

        get.beginControlFlow("if (result == null)")
            .addStatement("return empty()")
            .endControlFlow();
        get.addStatement("return wrap(result)");
        return get.build();
    }

    private static void emitRetrieve(MethodSpec.Builder get, GetterSpec spec, ClassName holderClass) {
        if (spec.retrieveIsRestAction) {
            get.addStatement("result = $T.$L(scope, id).complete()", holderClass, spec.retrieveMethod);
        } else {
            get.addStatement("result = $T.$L(scope, id)", holderClass, spec.retrieveMethod);
        }
    }

    private record ScopePattern(Scope scope, ClassName scopeClass, String patternSuffix) {}

    private static ScopePattern scopePattern(Scope scope) {
        return switch (scope) {
            case BOT -> new ScopePattern(scope, SkriptTypes.BOT,
                " [(with|using) [the] [bot] %-bot%]");
            case GUILD -> new ScopePattern(scope, SkriptTypes.GUILD,
                " (in|from) [the] [guild] %guild%");
            case CHANNEL -> new ScopePattern(scope, SkriptTypes.MESSAGE_CHANNEL,
                " (in|from) [the] [text] [channel] %messagechannel%");
        };
    }

    private static TypeName WildcardExpression() {
        return ParameterizedTypeName.get(SkriptTypes.EXPRESSION, WildcardTypeName.subtypeOf(Object.class));
    }
}
