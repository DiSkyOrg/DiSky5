package net.itsthesky.disky5.processor.writers;

import com.squareup.javapoet.*;
import net.itsthesky.disky5.processor.DiSkyProcessor.MultiTypeContribution;
import net.itsthesky.disky5.processor.util.NameUtils;
import net.itsthesky.disky5.processor.util.SkriptTypes;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.function.Predicate;

public final class MultiTypePropertyWriter {
    private MultiTypePropertyWriter() {}

    public static final String PACKAGE = "net.itsthesky.disky5.generated";

    public static void write(ProcessingEnvironment env, Map<String, List<MultiTypeContribution>> byName,
                             List<String> generatedClasses) throws IOException {
        for (Map.Entry<String, List<MultiTypeContribution>> entry : byName.entrySet()) {
            TypeSpec cls = build(entry.getKey(), entry.getValue());
            JavaFile.builder(PACKAGE, cls).build().writeTo(env.getFiler());
            generatedClasses.add(PACKAGE + "." + cls.name);
        }
    }

    private static TypeSpec build(String name, List<MultiTypeContribution> group) {
        String className = "PropMulti" + NameUtils.toClassName(name);

        Set<String> elementFqns = new LinkedHashSet<>();
        for (MultiTypeContribution c : group) elementFqns.add(c.elementTypeFqn());
        ClassName elementClass = elementFqns.size() == 1
            ? ClassName.bestGuess(elementFqns.iterator().next())
            : ClassName.get(Object.class);
        ArrayTypeName elementArray = ArrayTypeName.of(elementClass);

        boolean anyRetrieve = group.stream().anyMatch(c -> c.retrieve() != null);
        boolean allSingle   = group.stream().noneMatch(MultiTypeContribution::multi);
        boolean changeable  = group.stream().anyMatch(c -> c.setter() != null || c.adder() != null || c.remover() != null);

        List<String> codeNames = new ArrayList<>();
        for (MultiTypeContribution c : group) codeNames.add(c.codeName());
        String slot = "%" + String.join("/", codeNames) + "%";

        ParameterizedTypeName exprWild = ParameterizedTypeName.get(
            SkriptTypes.EXPRESSION, WildcardTypeName.subtypeOf(Object.class));

        TypeSpec.Builder cls = TypeSpec.classBuilder(className)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n"
                + "Union property '$L' of $L, dispatched by runtime type.\n", name, slot)
            .superclass(ParameterizedTypeName.get(SkriptTypes.SIMPLE_EXPRESSION, elementClass));

        cls.addStaticBlock(CodeBlock.of(
            "$T.registerExpression($L.class, $T.class, $T.PROPERTY, $S, $S);\n",
            SkriptTypes.SKRIPT, className, elementClass, SkriptTypes.EXPRESSION_TYPE,
            "[the] " + name + " of " + slot, slot + "'[s] " + name));

        cls.addField(exprWild, "source", Modifier.PRIVATE);

        cls.addMethod(MethodSpec.methodBuilder("init")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC).returns(boolean.class)
            .addParameter(ArrayTypeName.of(exprWild), "exprs")
            .addParameter(int.class, "matchedPattern")
            .addParameter(SkriptTypes.KLEENEAN, "isDelayed")
            .addParameter(SkriptTypes.PARSE_RESULT, "parseResult")
            .addStatement("this.source = exprs[0]")
            .addStatement("return true")
            .build());

        cls.addMethod(buildGet(group, elementClass, elementArray, anyRetrieve));

        cls.addMethod(MethodSpec.methodBuilder("isSingle")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC).returns(boolean.class)
            .addStatement(allSingle ? "return source.isSingle()" : "return false")
            .build());

        cls.addMethod(MethodSpec.methodBuilder("getReturnType")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(ParameterizedTypeName.get(ClassName.get(Class.class), WildcardTypeName.subtypeOf(elementClass)))
            .addStatement("return $T.class", elementClass)
            .build());

        if (changeable) {
            cls.addMethod(buildAcceptChange(group));
            if (partial(group, c -> c.setter() != null) || partial(group, c -> c.adder() != null)
                    || partial(group, c -> c.remover() != null) || partial(group, c -> c.setter() != null && c.setterArray()))
                cls.addMethod(buildWritable());
            cls.addMethod(buildChange(group));
        }

        cls.addMethod(MethodSpec.methodBuilder("toString")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC).returns(String.class)
            .addParameter(SkriptTypes.EVENT, "event").addParameter(boolean.class, "debug")
            .addStatement("return $S + source.toString(event, debug)", name + " of ")
            .build());

        return cls.build();
    }

    private static MethodSpec buildGet(List<MultiTypeContribution> group, ClassName elementClass,
                                       ArrayTypeName elementArray, boolean anyRetrieve) {
        MethodSpec.Builder get = MethodSpec.methodBuilder("get")
            .addAnnotation(Override.class).addModifiers(Modifier.PROTECTED).returns(elementArray)
            .addParameter(SkriptTypes.EVENT, "event");
        if (anyRetrieve)
            get.addStatement("boolean awaited = $T.isAwaited(event)", SkriptTypes.DISKY_ASYNC);
        get.addStatement("$T<$T> result = new $T<>()",
            ClassName.get("java.util", "List"), elementClass, ClassName.get("java.util", "ArrayList"));
        get.beginControlFlow("for ($T __o : source.getArray(event))", Object.class);
        boolean first = true;
        for (MultiTypeContribution c : group) {
            if (c.getter() == null && c.retrieve() == null) continue;
            if (first) { get.beginControlFlow("if (__o instanceof $T __e)", c.jdaType()); first = false; }
            else        get.nextControlFlow("else if (__o instanceof $T __e)", c.jdaType());
            emitRead(get, c, elementClass);
        }
        if (!first) get.endControlFlow();
        get.endControlFlow();
        get.addStatement("return result.toArray(new $T[0])", elementClass);
        return get.build();
    }

    private static void emitRead(MethodSpec.Builder get, MultiTypeContribution c, ClassName elementClass) {
        if (c.retrieve() != null) {
            get.beginControlFlow("if (awaited)");
            emitReadCall(get, c, true, elementClass);
            get.nextControlFlow("else");
            emitReadCall(get, c, false, elementClass);
            get.endControlFlow();
        } else {
            emitReadCall(get, c, false, elementClass);
        }
    }

    private static void emitReadCall(MethodSpec.Builder get, MultiTypeContribution c, boolean online, ClassName elementClass) {
        String method = online ? c.retrieve() : c.getter();
        boolean rest  = online && c.retrieveRest();
        String tail   = rest ? ".complete()" : "";
        if (c.multi()) {
            if (c.array() && !online)
                get.addStatement("result.addAll($T.asList($T.$L(__e)" + tail + "))",
                    ClassName.get("java.util", "Arrays"), c.descriptor(), method);
            else
                get.addStatement("result.addAll($T.$L(__e)" + tail + ")", c.descriptor(), method);
        } else {
            get.addStatement("$T __v = $T.$L(__e)" + tail, elementClass, c.descriptor(), method);
            get.addStatement("if (__v != null) result.add(__v)");
        }
    }

    private static MethodSpec buildAcceptChange(List<MultiTypeContribution> group) {
        Set<TypeName> set = new LinkedHashSet<>(), add = new LinkedHashSet<>(), rem = new LinkedHashSet<>(),
            del = new LinkedHashSet<>();
        List<ClassName> setW = new ArrayList<>(), addW = new ArrayList<>(), remW = new ArrayList<>(), delW = new ArrayList<>();
        for (MultiTypeContribution c : group) {
            if (c.setter() != null)  { set.add(c.setterArray() ? ArrayTypeName.of(c.setterValueType()) : c.setterValueType()); setW.add(c.jdaType()); }
            if (c.setter() != null && c.setterArray()) { del.add(ArrayTypeName.of(c.setterValueType())); delW.add(c.jdaType()); }
            if (c.adder() != null)   { add.add(ArrayTypeName.of(c.adderValueType())); addW.add(c.jdaType()); }
            if (c.remover() != null) { rem.add(ArrayTypeName.of(c.removerValueType())); remW.add(c.jdaType()); }
        }
        MethodSpec.Builder ac = MethodSpec.methodBuilder("acceptChange")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .returns(Class[].class).addParameter(SkriptTypes.CHANGER_MODE, "mode");
        ac.addStatement("$T<?> __rt = source.getReturnType()", Class.class);
        addAccept(ac, group, "SET", set, setW);
        addAccept(ac, group, "ADD", add, addW);
        addAccept(ac, group, "REMOVE", rem, remW);
        addAccept(ac, group, "DELETE", del, delW);
        ac.addStatement("return null");
        return ac.build();
    }

    // A source typed as a contributor that cannot take this mode (member in a role/member union) is refused
    // at parse time; an untyped or broader source is let through and dispatched at runtime.
    private static void addAccept(MethodSpec.Builder ac, List<MultiTypeContribution> group, String mode,
                                  Set<TypeName> types, List<ClassName> writers) {
        if (types.isEmpty()) return;
        List<ClassName> readers = new ArrayList<>();
        for (MultiTypeContribution c : group)
            if (!writers.contains(c.jdaType())) readers.add(c.jdaType());
        if (readers.isEmpty()) {
            ac.addStatement("if (mode == $T.$L) return $L", SkriptTypes.CHANGER_MODE, mode, classArray(types));
            return;
        }
        ac.addStatement("if (mode == $T.$L && writable(__rt, $L, $L)) return $L",
            SkriptTypes.CHANGER_MODE, mode, classList(writers), classList(readers), classArray(types));
    }

    private static CodeBlock classList(List<ClassName> types) {
        CodeBlock.Builder b = CodeBlock.builder().add("new Class<?>[]{ ");
        boolean f = true;
        for (ClassName t : types) { if (!f) b.add(", "); b.add("$T.class", t); f = false; }
        return b.add(" }").build();
    }

    private static boolean partial(List<MultiTypeContribution> group, Predicate<MultiTypeContribution> supports) {
        return group.stream().anyMatch(supports) && !group.stream().allMatch(supports);
    }

    private static MethodSpec buildWritable() {
        ParameterizedTypeName anyClass = ParameterizedTypeName.get(ClassName.get(Class.class), WildcardTypeName.subtypeOf(Object.class));
        return MethodSpec.methodBuilder("writable")
            .addModifiers(Modifier.PRIVATE, Modifier.STATIC).returns(boolean.class)
            .addParameter(anyClass, "type")
            .addParameter(ArrayTypeName.of(anyClass), "writers")
            .addParameter(ArrayTypeName.of(anyClass), "readers")
            .addStatement("for ($T w : writers) if (w.isAssignableFrom(type) || type.isAssignableFrom(w)) return true", anyClass)
            .addStatement("for ($T r : readers) if (r.isAssignableFrom(type)) return false", anyClass)
            .addStatement("return true")
            .build();
    }

    private static CodeBlock classArray(Set<TypeName> types) {
        CodeBlock.Builder b = CodeBlock.builder().add("new Class[]{ ");
        boolean f = true;
        for (TypeName t : types) { if (!f) b.add(", "); b.add("$T.class", t); f = false; }
        return b.add(" }").build();
    }

    private static MethodSpec buildChange(List<MultiTypeContribution> group) {
        boolean anyRest = group.stream().anyMatch(c ->
            (c.setter() != null && c.setterRest())
                || (c.adder() != null && c.adderRest())
                || (c.remover() != null && c.removerRest()));

        MethodSpec.Builder ch = MethodSpec.methodBuilder("change")
            .addAnnotation(Override.class).addModifiers(Modifier.PUBLIC)
            .addParameter(SkriptTypes.EVENT, "event")
            .addParameter(Object[].class, "delta")
            .addParameter(SkriptTypes.CHANGER_MODE, "mode");
        if (anyRest)
            ch.addStatement("boolean awaited = $T.isAwaited(event)", SkriptTypes.DISKY_ASYNC);
        ch.beginControlFlow("for ($T __o : source.getArray(event))", Object.class);
        ch.beginControlFlow("try");

        boolean firstType = true;
        for (MultiTypeContribution c : group) {
            if (c.setter() == null && c.adder() == null && c.remover() == null) continue;
            if (firstType) { ch.beginControlFlow("if (__o instanceof $T __e)", c.jdaType()); firstType = false; }
            else            ch.nextControlFlow("else if (__o instanceof $T __e)", c.jdaType());

            boolean openMode = false;
            if (c.setter() != null) {
                if (c.setterArray())
                    ch.beginControlFlow("if (mode == $T.SET || mode == $T.DELETE)",
                        SkriptTypes.CHANGER_MODE, SkriptTypes.CHANGER_MODE);
                else
                    ch.beginControlFlow("if (mode == $T.SET)", SkriptTypes.CHANGER_MODE);
                emitSet(ch, c);
                openMode = true;
            }
            if (c.adder() != null) {
                if (openMode) ch.nextControlFlow("else if (mode == $T.ADD)", SkriptTypes.CHANGER_MODE);
                else          ch.beginControlFlow("if (mode == $T.ADD)", SkriptTypes.CHANGER_MODE);
                if (c.adderArray()) emitArrayCall(ch, c.descriptor(), c.adder(), c.adderValueType(), c.adderRest());
                else emitElementLoop(ch, c.descriptor(), c.adder(), c.adderValueType(), c.adderRest());
                openMode = true;
            }
            if (c.remover() != null) {
                if (openMode) ch.nextControlFlow("else if (mode == $T.REMOVE)", SkriptTypes.CHANGER_MODE);
                else          ch.beginControlFlow("if (mode == $T.REMOVE)", SkriptTypes.CHANGER_MODE);
                if (c.removerArray()) emitArrayCall(ch, c.descriptor(), c.remover(), c.removerValueType(), c.removerRest());
                else emitElementLoop(ch, c.descriptor(), c.remover(), c.removerValueType(), c.removerRest());
                openMode = true;
            }
            if (openMode) ch.endControlFlow();
        }
        for (MultiTypeContribution c : group) {
            if (c.setter() != null || c.adder() != null || c.remover() != null) continue;
            if (firstType) { ch.beginControlFlow("if (__o instanceof $T)", c.jdaType()); firstType = false; }
            else            ch.nextControlFlow("else if (__o instanceof $T)", c.jdaType());
            ch.addStatement("throw new $T($S)", UnsupportedOperationException.class,
                "the " + c.name() + " of " + ("aeiou".indexOf(c.codeName().charAt(0)) >= 0 ? "an " : "a ")
                    + c.codeName() + " cannot be changed");
        }
        if (!firstType) ch.endControlFlow();

        ch.nextControlFlow("catch ($T __ex)", Throwable.class)
          .addStatement("$T.error(__ex, null, event)", SkriptTypes.DISKY_RUNTIME_HANDLER)
          .endControlFlow();
        ch.endControlFlow();
        return ch.build();
    }

    private static void emitSet(MethodSpec.Builder ch, MultiTypeContribution c) {
        CodeBlock value = c.setterArray()
            ? CodeBlock.of("delta == null ? new $T[0] : $T.copyOf(delta, delta.length, $T[].class)",
                c.setterValueType(), ClassName.get("java.util", "Arrays"), c.setterValueType())
            : CodeBlock.of("delta == null ? null : ($T) delta[0]", c.setterValueType());
        if (c.setterRest()) {
            ch.addStatement("$T action = $T.$L(__e, $L)",
                SkriptTypes.REST_ACTION, c.descriptor(), c.setter(), value);
            emitQueueOrComplete(ch);
        } else {
            ch.addStatement("$T.$L(__e, $L)", c.descriptor(), c.setter(), value);
        }
    }

    private static void emitArrayCall(MethodSpec.Builder ch, ClassName descriptor, String method,
                                      ClassName valueType, boolean rest) {
        CodeBlock value = CodeBlock.of("delta == null ? new $T[0] : $T.copyOf(delta, delta.length, $T[].class)",
            valueType, ClassName.get("java.util", "Arrays"), valueType);
        if (rest) {
            ch.addStatement("$T action = $T.$L(__e, $L)", SkriptTypes.REST_ACTION, descriptor, method, value);
            emitQueueOrComplete(ch);
        } else {
            ch.addStatement("$T.$L(__e, $L)", descriptor, method, value);
        }
    }

    private static void emitElementLoop(MethodSpec.Builder ch, ClassName descriptor, String method,
                                        ClassName valueType, boolean rest) {
        ch.beginControlFlow("for ($T raw : delta)", Object.class)
          .addStatement("$T value = ($T) raw", valueType, valueType);
        if (rest) {
            ch.addStatement("$T action = $T.$L(__e, value)", SkriptTypes.REST_ACTION, descriptor, method);
            emitQueueOrComplete(ch);
        } else {
            ch.addStatement("$T.$L(__e, value)", descriptor, method);
        }
        ch.endControlFlow();
    }

    private static void emitQueueOrComplete(MethodSpec.Builder ch) {
        ch.beginControlFlow("if (awaited)")
          .addStatement("action.complete()")
          .nextControlFlow("else")
          .addStatement("action.queue()")
          .endControlFlow();
    }
}
