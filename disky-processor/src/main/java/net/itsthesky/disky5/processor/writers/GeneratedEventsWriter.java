package net.itsthesky.disky5.processor.writers;

import com.squareup.javapoet.*;
import net.itsthesky.disky5.processor.DiSkyProcessor.EventRegistration;
import net.itsthesky.disky5.processor.DiSkyProcessor.EventValueReg;
import net.itsthesky.disky5.processor.util.SkriptTypes;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;

public final class GeneratedEventsWriter {
    private GeneratedEventsWriter() {}

    public static final String PACKAGE = "net.itsthesky.disky5.generated";

    public static void write(ProcessingEnvironment env, List<EventRegistration> events) throws IOException {
        MethodSpec.Builder reg = MethodSpec.methodBuilder("registerAll")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC);

        for (EventRegistration e : events) {
            reg.addStatement("$T.registerEvent($S, $T.class, $T.class, $L)",
                SkriptTypes.SKRIPT, e.name(), e.skriptEvent(), e.bukkitEvent(), patternLiterals(e.patterns()));
            reg.addStatement("$T.registerEventValue($T.class, $T.class, $T::getBot, 0)",
                SkriptTypes.EVENT_VALUES, e.bukkitEvent(), SkriptTypes.BOT, e.bukkitEvent());
            for (EventValueReg v : e.values()) {
                if (v.restGetter() != null) {
                    reg.addStatement("$T.registerEventValue($T.class, $T.class, ($T ev) -> ev.$L(), $L)",
                        SkriptTypes.EVENT_VALUES, e.bukkitEvent(), v.valueType(), e.bukkitEvent(),
                        v.restGetter(), v.time());
                } else if (v.channelFilter()) {
                    reg.addStatement("$T.registerEventValue($T.class, $T.class, ($T ev) -> $T.$L(($T) ev.getJdaEvent()) instanceof $T cv ? cv : null, $L)",
                        SkriptTypes.EVENT_VALUES, e.bukkitEvent(), v.valueType(), e.bukkitEvent(),
                        e.descriptor(), v.method(), v.paramType(), v.valueType(), v.time());
                } else {
                    reg.addStatement("$T.registerEventValue($T.class, $T.class, ($T ev) -> $T.$L(($T) ev.getJdaEvent()), $L)",
                        SkriptTypes.EVENT_VALUES, e.bukkitEvent(), v.valueType(), e.bukkitEvent(),
                        e.descriptor(), v.method(), v.paramType(), v.time());
                }
            }
            for (com.squareup.javapoet.ClassName expr : e.expressionClasses())
                reg.addStatement("$T.register()", expr);
        }

        TypeSpec cls = TypeSpec.classBuilder("GeneratedEvents")
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build())
            .addMethod(reg.build())
            .build();

        JavaFile.builder(PACKAGE, cls).build().writeTo(env.getFiler());
    }

    private static CodeBlock patternLiterals(List<String> patterns) {
        List<CodeBlock> parts = new ArrayList<>();
        for (String p : patterns) parts.add(CodeBlock.of("$S", p));
        return CodeBlock.join(parts, ", ");
    }
}
