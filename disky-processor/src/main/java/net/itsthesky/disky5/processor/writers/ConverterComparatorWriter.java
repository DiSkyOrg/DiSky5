package net.itsthesky.disky5.processor.writers;

import com.squareup.javapoet.JavaFile;
import com.squareup.javapoet.MethodSpec;
import com.squareup.javapoet.TypeSpec;
import net.itsthesky.disky5.processor.DiSkyProcessor.ComparatorInfo;
import net.itsthesky.disky5.processor.DiSkyProcessor.ConverterInfo;
import net.itsthesky.disky5.processor.util.SkriptTypes;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.util.List;

public final class ConverterComparatorWriter {
    private ConverterComparatorWriter() {}

    public static void writeConverters(ProcessingEnvironment env, List<ConverterInfo> converters) throws IOException {
        MethodSpec.Builder register = MethodSpec.methodBuilder("register")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC);

        for (ConverterInfo c : converters) {
            register.addStatement("$T.registerConverter($T.class, $T.class, from -> $T.$L(from))",
                SkriptTypes.CONVERTERS, c.from(), c.to(), c.owner(), c.method());
        }

        TypeSpec cls = TypeSpec.classBuilder("GeneratedConverters")
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build())
            .addMethod(register.build())
            .build();

        JavaFile.builder("net.itsthesky.disky5.generated", cls).build().writeTo(env.getFiler());
    }

    public static void writeComparators(ProcessingEnvironment env, List<ComparatorInfo> comparators) throws IOException {
        MethodSpec.Builder register = MethodSpec.methodBuilder("register")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC);

        for (ComparatorInfo c : comparators) {
            if (c.returnsBoolean())
                register.addStatement("$T.registerComparator($T.class, $T.class, (a, b) -> $T.get($T.$L(a, b)))",
                    SkriptTypes.COMPARATORS, c.t1(), c.t2(), SkriptTypes.RELATION, c.owner(), c.method());
            else
                register.addStatement("$T.registerComparator($T.class, $T.class, (a, b) -> $T.$L(a, b))",
                    SkriptTypes.COMPARATORS, c.t1(), c.t2(), c.owner(), c.method());
        }

        TypeSpec cls = TypeSpec.classBuilder("GeneratedComparators")
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Auto-generated by DiSkyProcessor - do not edit.\n")
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build())
            .addMethod(register.build())
            .build();

        JavaFile.builder("net.itsthesky.disky5.generated", cls).build().writeTo(env.getFiler());
    }
}
